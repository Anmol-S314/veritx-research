import { test, expect } from '@playwright/test';

test('persistent flow fixture: edit → compile → evaluate → inspect → study → adopt → compile', async ({ page, request }) => {
  test.skip(process.env.VERITX_LIVE_TEST !== '1', 'Explicit opt-in for real backend execution.');
  test.setTimeout(240000);
  page.setDefaultTimeout(15000);
  const projects = await (await request.get('/gw/api/v1/projects')).json();
  const project = projects.projects.find((row: any) => row.project.name === 'Flow test 01 · Dense decode · measured baseline');
  expect(project).toBeTruthy();
  const id = project.project.project_id;
  await page.goto('/#/shared/projects');
  await page.getByRole('row').filter({ hasText: id }).getByRole('button', { name: 'Load', exact: true }).click();
  await page.goto('/#/workloads/workflow');
  await page.getByRole('tab', { name: 'Fabric', exact: true }).click();
  await page.getByRole('tab', { name: 'Physical assumptions', exact: true }).click();
  const clock = page.getByRole('spinbutton', { name: 'Clock frequency (MHz)', exact: true });
  await clock.fill((Number(await clock.inputValue()) + 10).toString());
  await page.getByRole('button', { name: 'Validate topology', exact: true }).click();
  await expect(page.getByText('Topology accepted', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page.getByText('Saved draft differs from the revision.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Compile draft', exact: true }).click();
  await expect(page.getByText('Draft matches the revision.', { exact: true })).toBeVisible({ timeout: 30000 });
  const compiled = await (await request.get(`/gw/api/v1/projects/${id}`)).json();
  const revision = compiled.active_revision_id;
  await page.goto('/#/analysis/summary');
  const launcher = page.getByRole('button', { name: 'Run new evaluation' });
  if (await launcher.count()) await launcher.click();
  const network = page.getByRole('checkbox', { name: 'Select NETWORK_COMPLETION', exact: true });
  await expect(network).toBeEnabled({ timeout: 30000 });
  for (const box of await page.getByRole('checkbox', { name: /^Select / }).all()) if (await box.isEnabled()) await box.uncheck();
  await network.check();
  await page.getByRole('checkbox', { name: /I understand this runs real backend/ }).check();
  await page.getByRole('button', { name: 'Launch 1 analysis', exact: true }).click();
  await expect(page.getByText('Run published', { exact: false }).first()).toBeVisible({ timeout: 90000 });
  await page.goto('/#/analysis/metrics');
  await expect(page.getByText('completion_cycles', { exact: true }).first()).toBeVisible();
  await page.reload();
  await expect(page.getByText('completion_cycles', { exact: true }).first()).toBeVisible();
  await page.screenshot({ path: 'test-results/flow-measured-analysis.png', fullPage: true });
  await page.goto('/#/explore/brief');
  await page.getByRole('button', { name: /Bounded study/ }).click();
  await page.getByRole('checkbox', { name: /Approve this revision/ }).check();
  await page.getByRole('button', { name: 'Launch bounded study', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Download study results', exact: true })).toBeVisible({ timeout: 90000 });
  const select = page.getByLabel('Candidate to adopt');
  const options = await select.locator('option').allTextContents();
  expect(options.length).toBeGreaterThan(1);
  const currentDraft = await (await request.get(`/gw/api/v1/projects/${id}/draft`)).json();
  const currentWidth = (currentDraft.request.noc_controls ?? currentDraft.request.noc_config).link_width;
  const studyProject = await (await request.get(`/gw/api/v1/projects/${id}`)).json();
  const study = await (await request.get(`/gw/api/v1/optimizations/${studyProject.latest_optimization_study.optimization_id}`)).json();
  const different = study.study.candidates.find((candidate: any) => candidate.guided_patch.link_width !== currentWidth && candidate.compilation_status === 'COMPILED');
  expect(different).toBeTruthy();
  await select.selectOption({ label: different.candidate_id });
  await page.getByRole('checkbox', { name: /Apply this reviewed candidate/ }).check();
  await page.getByRole('button', { name: 'Adopt candidate with recovery snapshot' }).click();
  await expect.poll(async () => (await (await request.get(`/gw/api/v1/projects/${id}/draft`)).json()).dirty).toBe(true);
  await page.goto('/#/workloads/workflow');
  await page.getByRole('button', { name: 'Compile draft', exact: true }).click();
  await expect.poll(async () => (await (await request.get(`/gw/api/v1/projects/${id}`)).json()).active_revision_id, { timeout: 30000 }).not.toBe(revision);
  const after = await (await request.get(`/gw/api/v1/projects/${id}`)).json();
  expect(after.runs.some((run: any) => run.revision_id === after.active_revision_id)).toBe(false);
  expect(after.runs.some((run: any) => run.revision_id === revision)).toBe(true);
  await page.screenshot({ path: 'test-results/flow-adopted-revision.png', fullPage: true });
  await page.goto('/#/analysis/summary');
  const rerun = page.getByRole('button', { name: 'Run new evaluation' });
  if (await rerun.count()) await rerun.click();
  await expect(page.getByRole('checkbox', { name: 'Select NETWORK_COMPLETION', exact: true })).toBeEnabled({ timeout: 30000 });
  for (const box of await page.getByRole('checkbox', { name: /^Select / }).all()) if (await box.isEnabled()) await box.uncheck();
  await page.getByRole('checkbox', { name: 'Select NETWORK_COMPLETION', exact: true }).check();
  await page.getByRole('checkbox', { name: /I understand this runs real backend/ }).check();
  await page.getByRole('button', { name: 'Launch 1 analysis', exact: true }).click();
  await expect(page.getByText('Run published', { exact: false }).first()).toBeVisible({ timeout: 90000 });
  const evaluated = await (await request.get(`/gw/api/v1/projects/${id}`)).json();
  expect(evaluated.runs.some((run: any) => run.revision_id === after.active_revision_id)).toBe(true);
  await page.goto('/#/workloads/workflow');
  const oldRevision = page.getByRole('button', { name: new RegExp(`${revision.split('-').pop()} .*COMPILED`) });
  if (await oldRevision.count()) {
    if (await oldRevision.getAttribute('aria-expanded') !== 'true') await oldRevision.click();
    const row = page.getByRole('row').filter({ hasText: `${revision.split('-').pop()} · run` }).first();
    await row.getByRole('button', { name: 'Open analysis', exact: true }).click();
    await expect(page.getByText(/Viewing .*historical|Viewing r/).first()).toBeVisible();
  }
});
