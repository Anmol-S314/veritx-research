def _write_run(tmp_path: Path, *, with_fabric: bool) -> Path:
    run = tmp_path / "run1"
    (run / "artifacts").mkdir(parents=True)
    (run / "workload").mkdir(parents=True)  # certified workload identity
    (run / "workload" / "index.json").write_text(json.dumps({
        "schema_version": 1,
        "artifacts": [{"trace": "trace/r0.txt",
                       "artifact_hash": "sha256:" + "c" * 64}]}))
    (run / "spec.resolved.json").write_text(json.dumps({
        "workload": {"id": "w", "trace": "archive/inputs/traces/x.trace"},
        "system": {"nodes": 8, "tp_size": 2, "instances_per_node": 1},
        "simulation": {"mode": "serving", "timeout_s": 60},
        "replication": {"mode": "deterministic", "seeds": [42]},
        "serving": {"cluster": "single_tp2_ep2", "dataset": "example",
                    "num_reqs": 1, "network_backend": "booksim",
                    "cycle_accurate": True,
                    "request_routing_policy": "LOAD"},
    }))
    results = [{
        "task_id": "serve",
        "provenance": {"engine": "llmservingsim",
                       "network_backend": "booksim",
                       "network_mode": "REAL_SIMULATION",
                       "semantic_losses": [],
                       "fidelity": "SYSTEM_SERVING_SIMULATION"},
        "metric_schema": 1,
        "metrics": {"TTFT": {"value": 1.0, "unit": "ns",
                             "producer": "llmservingsim",
                             "fidelity": "SYSTEM_SERVING_SIMULATION",
                             "scope": "per_request"}},
    }]
    if with_fabric:
        results[0]["executed_fabric"] = {
            "topology": "mesh", "size": {"k": "2", "n": "1"},
            "routing": "dor", "num_vcs": "16", "vc_buf_size": "512",
            "packet_size": "64",
            "config_sha256": "sha256:" + "a" * 64,
            "network_yml_sha256": "sha256:" + "b" * 64,
        }
    (run / "manifest.json").write_text(json.dumps(
        {"schema_version": 1, "run_id": "run1", "status": "SUCCEEDED",
         "results": results}))
    return run


class TestComparisonCertification:
    def test_no_executed_fabric_is_insufficient_provenance(self, tmp_path):
        """Pin K: absence of evidence is not equality. vc/packetization
        unresolved ⇒ certified=False + INSUFFICIENT_PROVENANCE."""
        from veritx_dse.core.comparison import fingerprint_from_run
        fp = fingerprint_from_run(_write_run(tmp_path, with_fabric=False))
        assert fp["vc_count"] is None
        assert fp["packetization"] is None
        assert fp["certified"] is False
        assert fp["certification_status"] == "INSUFFICIENT_PROVENANCE"
        assert "vc_count" in fp["unresolved_dimensions"]
        assert "packetization" in fp["unresolved_dimensions"]

    def test_executed_fabric_resolves_identity_and_certifies(self, tmp_path):
        from veritx_dse.core.comparison import fingerprint_from_run
        fp = fingerprint_from_run(_write_run(tmp_path, with_fabric=True))
        assert fp["vc_count"] == 16
        assert fp["packetization"] == 64
        assert fp["topology"] == "mesh"      # executed evidence, serving
        assert fp["routing"] == "dor"
        assert fp["certified"] is True
        assert fp["certification_status"] == "RESOLVED"
        assert fp["executed_topology"] == "mesh"
        assert fp["executed_config_sha256"].startswith("sha256:")

    def test_two_nones_are_not_equality(self, tmp_path):
        """Two candidates that BOTH fail to record vc_count must not pass
        certification because 'both are None' — shared ignorance is not
        equality."""
        from veritx_dse.core.comparison import (
            evaluate_comparability, fingerprint_from_run)
        run_a = _write_run(tmp_path / "a", with_fabric=False)
        run_b = _write_run(tmp_path / "b", with_fabric=False)
        (tmp_path / "a").mkdir(parents=True, exist_ok=True)
        fp_a = fingerprint_from_run(run_a)
        fp_b = fingerprint_from_run(run_b)
        assert not fp_a["certified"] and not fp_b["certified"]
        verdict = evaluate_comparability(
            [fp_a, fp_b],
            {"kind": "DESIGN_COMPARISON", "objectives": ["latency"],
             "experimental_variables": [], "controlled_dimensions": {}})
        assert verdict.certified is False

    def test_legacy_rows_stay_uncertified(self):
        from veritx_dse.core.comparison import fingerprint_from_legacy_row
        fp = fingerprint_from_legacy_row({
            "topology": "mesh_4x4", "nodes": 16, "seed": 0,
            "latency": 100.0})
        assert fp["certified"] is False
        assert "vc_count" in fp["unresolved_dimensions"]


# ── rank-assignment-preserving workload identity (P0 #11) ──────────────

class TestWorkloadIdentityRankAssignment:
    def _index(self, pairs):
        return {"artifacts": [
            {"trace": t, "artifact_hash": h} for t, h in pairs]}

    def test_identity_preserves_rank_assignment(self):
        """Pin G: rank0=A,rank1=B ≠ rank0=B,rank1=A despite an identical
        artifact multiset — the old sorted-hash-set digest was blind to
        rank assignment."""
        from veritx_dse.workload.serve import workload_identity
        ab = self._index([("trace/r0.txt", "sha256:aaa"),
                          ("trace/r1.txt", "sha256:bbb")])
        ba = self._index([("trace/r0.txt", "sha256:bbb"),
                          ("trace/r1.txt", "sha256:aaa")])
        assert workload_identity(ab) != workload_identity(ba)

    def test_same_assignment_same_identity(self):
        from veritx_dse.workload.serve import workload_identity
        i1 = self._index([("trace/r0.txt", "sha256:aaa"),
                          ("trace/r1.txt", "sha256:bbb")])
        i2 = self._index([("trace/r0.txt", "sha256:aaa"),
                          ("trace/r1.txt", "sha256:bbb")])
        assert workload_identity(i1) == workload_identity(i2)

    def test_identity_canonicalizes_by_rank_key(self):
        """The digest canonicalizes by trace path (rank key), never by
        sorting artifact hashes — assignment survives hashing."""
        from veritx_dse.workload.serve import workload_identity
        listed = self._index([("trace/r1.txt", "sha256:bbb"),
                              ("trace/r0.txt", "sha256:aaa")])
        ordered = self._index([("trace/r0.txt", "sha256:aaa"),
                               ("trace/r1.txt", "sha256:bbb")])
        assert workload_identity(listed) == workload_identity(ordered)

    def test_single_artifact_identity_unchanged(self):
        from veritx_dse.workload.serve import workload_identity
        assert workload_identity(self._index(
            [("trace/r0.txt", "sha256:aaa")])) == "sha256:aaa"

    def test_empty_index_fail_closed(self):
        from veritx_dse.workload.canonical import WorkloadError
        from veritx_dse.workload.serve import workload_identity
        with pytest.raises(WorkloadError):
            workload_identity({"artifacts": []})


