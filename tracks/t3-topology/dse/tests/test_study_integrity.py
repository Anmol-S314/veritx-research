# ── T3 failure propagation (P0 #9: a failed child cannot read as done) ──

class TestT3FailurePropagation:
    """Functional shell test: source the real t3 in a subshell, force the
    guided-flow child to exit 7, and prove failure propagates."""

    T3 = Path(__file__).parents[2] / "t3"

    def _bash(self, script: str) -> subprocess.CompletedProcess:
        return subprocess.run(
            ["bash", "-c", script], capture_output=True, text=True,
            timeout=30, env={**os.environ, "TERM": "dumb"})

    def test_ui_open_returns_child_rc(self):
        """Pin L (part 1): ``_ui_open`` ends with ``return "$_rc"`` — the
        regression that made a failed step invisible to guided flows
        (they marched on and announced success). The full functional call
        lives behind t3's container dispatch, so the contract is pinned
        textually plus the chain semantics functionally below."""
        text = self.T3.read_text()
        body = text.split("_ui_open() {", 1)[1].split("\n_ui_", 1)[0]
        assert 'return "$_rc"' in body
        # And the failure is PRINTED (observable to the human too).
        assert 'failed (exit $_rc)' in body

    def test_start_here_chain_short_circuits_on_failure(self):
        """Pin L (part 2): the guided-flow shape ``step || return`` must
        never run step 2 after step 1 fails, and the flow exits nonzero."""
        r = self._bash(
            'step() { return 7; }; '
            'step || { echo "step1 failed"; exit 7; }; '
            'echo UNREACHABLE')
        assert r.returncode == 7
        assert "UNREACHABLE" not in r.stdout


