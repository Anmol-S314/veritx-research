# ── helpers ─────────────────────────────────────────────────────────────

def _cfg(tmp_path: Path, body: str) -> Path:
    d = tmp_path / "inputs" / "booksim"
    d.mkdir(parents=True, exist_ok=True)
    p = d / "config.cfg"
    p.write_text(textwrap.dedent(body))
    return p


def _anynet(tmp_path: Path, nodes: int = 3) -> Path:
    d = tmp_path / "inputs" / "booksim"
    d.mkdir(parents=True, exist_ok=True)
    (d / "topo.anynet").write_text(
        "".join(f"router {i} node {i}\n" for i in range(nodes)))
    (d / "config.cfg").write_text(
        f"topology = anynet;\nnetwork_file = {d / 'topo.anynet'};\n"
        "routing_function = min;\nnum_vcs = 16;\npacket_size = 64;\n")
    return d / "config.cfg"


