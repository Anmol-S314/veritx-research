"""Study-integrity regression pins — post-freeze adversarial-review fixes.

Wave-A authority contract:

  * serving: the CLUSTER is the fabric intent. The slice resolves the
    expected cluster-derived fabric BEFORE Run.create (it rides the
    experiment hash), records the executed fabric, and fails the run
    closed unless expected == executed. A serving spec may not carry a
    standalone network preset at all.
  * standalone: a named preset OWNS its routing; ``routing=None`` means
    "no opinion" and resolves to the preset's native routing; anything
    else is rejected before a run directory exists.
  * compiler: failure/unmeasurable/pruned is never NO_FEASIBLE_DESIGN.
  * comparison: a mandatory dimension that is None on BOTH sides is
    unresolved, not equal — certification requires recorded evidence.

Each test names the defect it pins. These are fast, simulator-free pins
at the seams; live end-to-end behavior stays with the slice tests.
"""
