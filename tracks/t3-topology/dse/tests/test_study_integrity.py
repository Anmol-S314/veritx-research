def _k2n1_cfg(*, k: int = 2) -> Path:
    """One-shot tmp mesh config in the child's exact template form."""
    import tempfile
    root = Path(tempfile.mkdtemp(prefix="fabric-"))
    body = MESH_2x2.replace("k = 2;", f"k = {k};").replace("n = 2;", "n = 1;")
    return _cfg(root, body)


# ── compiler verdict honesty (P0 #3/#6: failure ≠ infeasible) ──────────

class TestCompilerVerdictHonesty:
    def _compile(self, candidates, evaluate):
        from veritx_dse.synthesis.compiler import CompilerRequest, compile_fabric
        req = CompilerRequest(
            requirements=[{"qos_class": "latency_critical",
                           "latency_ceiling_cycles": 100.0, "binding": True}],
            candidates=candidates)
        return compile_fabric(req, evaluate)

    def test_all_evaluations_fail_is_evaluation_failed(self):
        """Pin H: every evaluator crash ⇒ EVALUATION_FAILED, never
        NO_FEASIBLE_DESIGN."""
        def boom(cand):
            raise RuntimeError("booksim timeout")
        out = self._compile([{"name": "a"}, {"name": "b"}], boom)
        assert out["verdict"] == "EVALUATION_FAILED"
        assert out["failure_reasons"]["evaluation_failed"] == 2
        assert out["pareto"] is None
        assert out["relaxation_information"] is None

    def test_violations_plus_failures_is_evaluation_failed(self):
        """Pin I: 4 violations + 6 failures ⇒ EVALUATION_FAILED (the
        evidence problem dominates the refusal)."""
        def mixed(cand):
            if int(cand["name"]) >= 4:
                raise RuntimeError("sim died")
            return {"name": cand["name"], "topology": "anynet",
                    "backend": "anynet", "nodes": 16, "edges": 32,
                    "latency": 500.0, "status": "ok", "error": None,
                    "seed": 0, "provenance": "stub", "extra": {}}
        out = self._compile([{"name": str(i)} for i in range(10)], mixed)
        assert out["verdict"] == "EVALUATION_FAILED"

    def test_all_unmeasurable_is_constraint_unmeasurable(self):
        """10 unmeasurable ⇒ CONSTRAINT_UNMEASURABLE. Unmeasurable means
        the required metric has NO measured producer (here: a binding
        bandwidth_floor the stack cannot measure) — distinct from an
        evaluation crash (latency=None ⇒ EVALUATION_FAILED)."""
        from veritx_dse.synthesis.compiler import CompilerRequest, compile_fabric

        def ok_latency(cand):
            return {"name": cand["name"], "topology": "anynet",
                    "backend": "anynet", "nodes": 16, "edges": 32,
                    "latency": 50.0, "status": "ok", "error": None,
                    "seed": 0, "provenance": "stub", "extra": {}}
        req = CompilerRequest(
            requirements=[{"qos_class": "latency_critical",
                           "bandwidth_floor_gbps": 10.0,
                           "binding": True}],
            candidates=[{"name": str(i)} for i in range(10)])
        out = compile_fabric(req, ok_latency)
        assert out["verdict"] == "CONSTRAINT_UNMEASURABLE"
        assert out["relaxation_information"] is None
        assert out["pareto"] is None

    def test_all_measured_violations_is_no_feasible_design(self):
        """Pin J: 10 successfully measured violations — the ONLY legal
        NO_FEASIBLE_DESIGN, and the only verdict carrying relaxation."""
        def violator(cand):
            return {"name": cand["name"], "topology": "anynet",
                    "backend": "anynet", "nodes": 16, "edges": 32,
                    "latency": 500.0, "status": "ok", "error": None,
                    "seed": 0, "provenance": "stub", "extra": {}}
        out = self._compile([{"name": str(i)} for i in range(10)], violator)
        assert out["verdict"] == "NO_FEASIBLE_DESIGN"
        assert out["violated_constraints"]
        assert out["relaxation_information"]  # valid: fully measured

    def test_violations_plus_pruned_is_search_incomplete(self):
        """4 violations + 6 pruned ⇒ SEARCH_INCOMPLETE (space not
        exhausted, and the evaluated subset alone must not refuse)."""
        from veritx_dse.synthesis import compiler as C
        verdict = C._verdict_from_counts(
            records=[{"status": C.ST_CONSTRAINT_VIOLATION}] * 4
                    + [{"status": C.ST_PRUNED}] * 6,
            n_feasible=0, n_violated=4, n_failed=0,
            n_unmeasurable=0, n_pruned=6)
        assert verdict == C.VERDICT_SEARCH_INCOMPLETE
        # And the pure decision order, pinned exactly:
        assert C._verdict_from_counts(
            records=[{"status": C.ST_CONSTRAINT_VIOLATION}] * 10,
            n_feasible=0, n_violated=10, n_failed=0,
            n_unmeasurable=0, n_pruned=0) == C.VERDICT_NO_FEASIBLE_DESIGN
        assert C._verdict_from_counts(
            records=[], n_feasible=0, n_violated=0, n_failed=0,
            n_unmeasurable=0, n_pruned=0) == C.VERDICT_SEARCH_INCOMPLETE

    def test_one_feasible_among_failures_is_feasible(self):
        """1 feasible + 9 failures ⇒ FEASIBLE (a real design exists)."""
        def one_ok(cand):
            if cand["name"] == "good":
                return {"name": "good", "topology": "anynet",
                        "backend": "anynet", "nodes": 16, "edges": 32,
                        "latency": 50.0, "status": "ok", "error": None,
                        "seed": 0, "provenance": "stub", "extra": {}}
            raise RuntimeError("sim died")
        out = self._compile([{"name": str(i)} for i in range(9)]
                            + [{"name": "good"}], one_ok)
        assert out["verdict"] == "FEASIBLE"
        assert out["pareto"] is not None


