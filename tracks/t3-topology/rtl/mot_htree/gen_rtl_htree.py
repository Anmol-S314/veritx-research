# ── Routing tables ──────────────────────────────────────────────────────────

def dijkstra_tables(n, adj):
    """min next-hop port per (router,dst); ports = sorted neighbor order."""
    tbl = {}
    INF = 10**9
    for src in range(n):
        nbrs = sorted(adj[src])
        pidx = {nb: i for i, nb in enumerate(nbrs)}
        dist = [INF]*n; prev = [-1]*n; dist[src] = 0
        unvis = set(range(n))
        while unvis:
            u = min(unvis, key=lambda i: dist[i])
            unvis.discard(u)
            if dist[u] == INF: break
            for v in sorted(adj[u]):
                if dist[u]+1 < dist[v]:
                    dist[v] = dist[u]+1; prev[v] = u
        for dst in range(n):
            if dst == src: continue
            if prev[dst] == -1:
                tbl[(src, dst)] = 0; continue
            x = dst
            while prev[x] != src and prev[x] != -1:
                x = prev[x]
            tbl[(src, dst)] = pidx.get(x, 0)
    return tbl


def tree_tables(n, adj, root=0):
    """escape UP-FIRST (up*/down*) next-hop port per (router,dst).

    R3 FIX (2026-08-22): the old implementation emitted the first hop toward
    dst on the UNORDERED tree (LCA path computed, then path[1] taken). On any
    tree edge, flits then used BOTH directions in a single shared ESC VC ->
    2-cycles in the escape-class CDG -> the escape leg itself can deadlock
    (observed at 64n: esc=1 queues, full credits, held outputs, ages cycling,
    frozen 400k cycles; ring passed only because a rooted path is monotone).
    Fix: climb to the LCA using ONLY parent edges, then descend using only
    child edges. One VC, acyclic CDG, deadlock-free by construction.
    """
    rank = [-1]*n; par = [-1]*n; rank[root] = 0
    q = deque([root])
    while q:
        u = q.popleft()
        for v in sorted(adj[u]):
            if rank[v] < 0:
                rank[v] = rank[u]+1; par[v] = u; q.append(v)
    tbl = {}
    for s in range(n):
        nbrs = sorted(adj[s])
        pidx = {nb: i for i, nb in enumerate(nbrs)}
        for t in range(n):
            if t == s: continue
            # is t in s's subtree? (s ancestor of t)
            x = t
            while x != -1 and x != s:
                x = par[x]
            if x == s or par[s] == -1:
                # descend: child of s on the s->t path
                c = t
                while par[c] != s:
                    c = par[c]
                tbl[(s, t)] = pidx.get(c, 0)
            else:
                # climb: parent edge (up-first to the LCA)
                tbl[(s, t)] = pidx.get(par[s], 0)
    return tbl


