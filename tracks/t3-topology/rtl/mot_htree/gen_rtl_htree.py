#!/usr/bin/env python3
"""gen_rtl.py — 2-VC certified-per-VC NoC RTL generator.

Emits a self-contained, Verilator-verifiable SystemVerilog NoC for an
ARBITRARY topology with the certified-per-VC scheme:

  * MULTI-FLIT wormhole routers (HEAD/BODY/TAIL/SINGLE, 1..N flits/packet)
  * 2 VC classes: VC0=FREE (Dijkstra minimal), VC1=ESCAPE (up/down tree)
  * Credit-based flow control per (output_port, VC)
  * Demotion-on-block: head blocked > K cycles => switch to escape table
  * Strict escape priority in switch arbitration
  * Route tables loaded in noc_top.sv initial block (Verilator-clean)

Flit format (64 bits):
  [63]    = escape_class (0=free, 1=escape)
  [62:DST_W+48] = reserved
  [DST_W+47:48] = dst
  [47:0]  = src(8 bits) + payload(40 bits)

Usage:
  python3 gen_rtl.py --anynet .noc_p0/custom_v2.anynet --outdir .noc_p0/rtl16 --limit 16
  cd .noc_p0/rtl16 && make
  ./obj_dir/Vnoc_top
"""
