def emit_pkg(outdir, n, max_deg, vcs, buf, k_block):
    dst_w = max(1, math.ceil(math.log2(max(n, 2))))
    cred_w = max(1, math.ceil(math.log2(buf + 1)))        # per-(output,VC) buffer
    port_w = max(1, math.ceil(math.log2(max_deg + 1)))
    class_w = max(1, math.ceil(math.log2(max(vcs, 2))))    # VC class field width
    # QCNT_W: each queue counter counts per-queue occupancy (max BUF_DEPTH).
    # The old formula used 2*BUF for 2-VC shared; per-queue only needs BUF+1.
    qcnt_w = max(1, math.ceil(math.log2(buf + 1)))
    (outdir / "noc_pkg.sv").write_text(f"""\
// Generated by gen_rtl.py — do not edit
package noc_pkg;
  localparam int N_ROUTERS   = {n};
  localparam int MAX_DEG     = {max_deg};
  localparam int NUM_PORTS   = MAX_DEG + 1;  // +1 local
  localparam int LOCAL_PORT  = MAX_DEG;
  localparam int NUM_VCS     = {vcs};
  localparam int BUF_DEPTH   = {buf};
  localparam int FLIT_W      = 64;
  localparam int DST_W       = {dst_w};
  localparam int CLASS_W     = {class_w};  // VC class bits in flit header
  localparam int TYPE_W      = 2;   // flit type bits (below class field)
  // Flit layout (CLASS_W bits at top, TYPE_W below):
  //   [63:64-CLASS_W]  = traffic class (VC index: 0=free, 1..N-1=escape/priority)
  //   [63-CLASS_W:64-CLASS_W-TYPE_W] = type (HEAD=0 BODY=1 TAIL=2 SINGLE=3)
  localparam int CLASS_MSB   = FLIT_W - 1;
  localparam int CLASS_LSB   = FLIT_W - CLASS_W;
  localparam int TYPE_MSB    = CLASS_LSB - 1;
  localparam int TYPE_LSB    = CLASS_LSB - TYPE_W;
  localparam logic [TYPE_W-1:0] FT_HEAD   = 2'd0;
  localparam logic [TYPE_W-1:0] FT_BODY   = 2'd1;
  localparam logic [TYPE_W-1:0] FT_TAIL   = 2'd2;
  localparam logic [TYPE_W-1:0] FT_SINGLE = 2'd3;
  // Per-PORT credit (shared buffer across VCs), width = clog2(BUF_DEPTH+1)
  localparam int CRED_W      = {cred_w};
  // Queue-counter width: per-queue counter holds up to BUF_DEPTH.
  localparam int QCNT_W      = $clog2({buf} + 1);
  localparam int PORT_W      = {port_w};
  localparam int BLOCK_K     = {k_block};

  typedef struct packed {{
    logic [FLIT_W-1:0] raw;   // see layout comment in router.sv:
                              // [CLASS_MSB:CLASS_LSB]=class, [TYPE_MSB:TYPE_LSB]=type
  }} flit_t;

  // Flit wire (raw 64-bit for $readmemh compatibility)
  typedef logic [FLIT_W-1:0] flit_raw_t;
endpackage
""")


# ── Emit: noc_top.sv with inline route tables ───────────────────────────────

def emit_top(outdir, n, adj, tbl_min, tbl_esc, arch="legacy-vc", module_name="noc_top"):
    max_deg = max(len(adj[i]) for i in range(n))
    port_w = max(1, math.ceil(math.log2(max_deg + 1)))

    # Build port mapping: for each router, its neighbors in sorted order
    port_map = {}
    for r in range(n):
        nbrs = sorted(adj[r])
        port_map[r] = {nb: i for i, nb in enumerate(nbrs)}

    # Wire declarations (network links + local injection/ejection)
    wire_decls = []
    ready_assigns = []
    for r in range(n):
        nbrs = sorted(adj[r])
        for p in range(len(nbrs)):
            wire_decls.append(f"  noc_pkg::flit_raw_t net_flit_{r}_{p};")
            wire_decls.append(f"  logic       net_valid_{r}_{p};")
            wire_decls.append(f"  logic       net_ready_{r}_{p};")
            ready_assigns.append(f"  assign net_ready_{r}_{p} = nready_{r}_{p};")
        # Local port wires are module ports, not internal wires — skip decl here

    # Router instantiations
    router_insts = []
    unconn_ready_wires = []  # wires for unconnected/network ready signals
    for r in range(n):
        nbrs = sorted(adj[r])
        deg = len(nbrs)

        # Packed route-table parameters: PORT_W bits per dst, dst 0 in LSB.
        def pack(tbl):
            parts = [f"{port_w}'d{tbl.get((r, d), 0)}" for d in range(n)]
            return "{" + ", ".join(parts[::-1]) + "}"   # concat is MSB-first

        rt_min_p = pack(tbl_min)
        rt_esc_p = pack(tbl_esc)
        # Build port connection arrays (reversed for SystemVerilog {a,b} ordering)
        # Local port is index deg (the last index)
        in_flits  = ["64'd0"] * (max_deg + 1)
        in_valids = ["1'b0"] * (max_deg + 1)
        out_readys = ["1'b0"] * (max_deg + 1)
        in_readys  = ["1'b0"] * (max_deg + 1)
        out_flits  = ["64'd0"] * (max_deg + 1)
        out_valids = ["1'b0"] * (max_deg + 1)
        for p in range(deg):
            nb = nbrs[p]
            nb_port = port_map[nb][r]
            in_flits[p]   = f"net_flit_{nb}_{nb_port}"
            in_valids[p]  = f"net_valid_{nb}_{nb_port}"
            out_readys[p] = f"net_ready_{nb}_{nb_port}"
        # Network ready signals — EXACTLY deg entries (the router port is
        # [0:DEG-1]; unused ports are tied off INSIDE the router).
        in_readys_net = []
        for p in range(deg):
            wire_name = f"nready_{r}_{p}"
            unconn_ready_wires.append(f"  logic {wire_name};")
            in_readys_net.append(wire_name)
        # Drive each net_ready_{r}_{p} from router r's own in_ready (the
        # receiver owns the ready handshake of its incoming link).
        # (assigns emitted once in the wire-declaration loop above)
        # Local port (index deg)
        in_flits[deg]   = f"local_in_flit_{r}"
        in_valids[deg]  = f"local_in_valid_{r}"
        out_readys[deg] = f"local_out_ready_{r}"
        in_readys[deg]  = f"local_in_ready_{r}"
        out_flits[deg]  = f"local_out_flit_{r}"
        out_valids[deg] = f"local_out_valid_{r}"

        # Build wire names for outputs (per-port, for assign statements)
        out_flit_wires = []
        out_valid_wires = []
        for p in range(deg):
            nb = nbrs[p]
            out_flit_wires.append(f"net_flit_{r}_{p}")
            out_valid_wires.append(f"net_valid_{r}_{p}")
        # LOCAL port is separate — NOT in n_out_flit/n_out_valid arrays

        router_insts.append(f"""
  router #(.ID({r}), .DEG({deg}), .RT_MIN({rt_min_p}){(', .RT_ESC(' + rt_esc_p + ')') if arch != 'plane-v2' else ''}) u_router_{r} (
    .clk(clk), .rst_n(rst_n),
    // NOTE: ports are packed [0:DEG-1]; concat fills index 0 first, so NO
    // reversal — port p must map to sorted-neighbors[p] to match the tables.
    .n_in_flit({{ {', '.join(in_flits[0:deg])} }}),
    .n_in_valid({{ {', '.join(in_valids[0:deg])} }}),
    .n_in_ready({{ {', '.join(in_readys_net)} }}),
    .n_out_flit({{ {', '.join(out_flit_wires)} }}),
    .n_out_valid({{ {', '.join(out_valid_wires)} }}),
    .n_out_ready({{ {', '.join(out_readys[0:deg])} }}),
    .local_in_flit({in_flits[deg]}),
    .local_in_valid({in_valids[deg]}),
    .local_in_ready({in_readys[deg]}),
    .local_out_flit(local_out_flit_{r}),
    .local_out_valid(local_out_valid_{r}),
    .local_out_ready({out_readys[deg]})
  );""")

    # Route tables are passed as packed module parameters (RT_MIN/RT_ESC),
    # so no initial-block population is required.

    # Build local port declarations
    local_port_decls = []
    for r in range(n):
        local_port_decls.append(f"  output noc_pkg::flit_raw_t local_out_flit_{r},")
        local_port_decls.append(f"  output logic       local_out_valid_{r},")
        local_port_decls.append(f"  input  logic       local_out_ready_{r},")
        local_port_decls.append(f"  input  noc_pkg::flit_raw_t local_in_flit_{r},")
        local_port_decls.append(f"  input  logic       local_in_valid_{r},")
        local_port_decls.append(f"  output logic       local_in_ready_{r}")
    # Add commas except for last port
    for i in range(len(local_port_decls) - 1):
        local_port_decls[i] = local_port_decls[i].rstrip(',') + ','

    (outdir / f"{module_name}.sv").write_text(f"""\
// Generated by gen_rtl.py — {module_name} ({n} routers, {arch})
// Local injection/ejection ports: drive local_in_flit_{r}/local_in_valid_{r} to inject,
// monitor local_out_flit_{r}/local_out_valid_{r} to eject.
module {module_name} (
  input  logic clk,
  input  logic rst_n,
{chr(10).join(local_port_decls)}
);

  // Network wires
{chr(10).join(wire_decls)}

  // Internal ready wires (incl. unconnected-port ready signals)
{chr(10).join(unconn_ready_wires)}

  // Ready handshake: net_ready_{r}_{p} driven by receiver r's in_ready
{chr(10).join(ready_assigns)}

  // Router instantiations
{chr(10).join(router_insts)}

endmodule
""")


