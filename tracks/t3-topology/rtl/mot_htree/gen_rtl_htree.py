def _best_escape_root(n, adj):
    """Pick the most central node as escape tree root (min max-depth,
    tiebreak by min avg-depth → prefer center-of-mass nodes)."""
    from collections import deque
    best_root, best_maxd, best_avgd = 0, n, float('inf')
    for root in range(n):
        rank = [-1]*n; rank[root] = 0
        q = deque([root])
        while q:
            u = q.popleft()
            for v in sorted(adj[u]):
                if rank[v] < 0:
                    rank[v] = rank[u]+1; q.append(v)
        if all(r >= 0 for r in rank):
            md = max(rank)
            ad = sum(rank) / n
            if (md < best_maxd) or (md == best_maxd and ad < best_avgd):
                best_maxd = md; best_avgd = ad; best_root = root
    return best_root


def dim_order_tables(n, adj):
    """R6 FIX (Bug A root cause): strict dimension-order (row-first) routing.

    dijkstra_tables() computes shortest paths with ARBITRARY tie-breaks.
    On the 4x4 mesh those tie-breaks produced a cyclic channel dependency
    graph (proven cycle 1->0->4->5->1), enabling classic wormhole deadlock
    (~50 packets stuck at IR=0.08 on every seed).

    Dimension-order routing completes ALL horizontal moves before ANY
    vertical move, making the CDG provably acyclic on meshes (Dally-Seitz).
    Returns None if topology isn't a row-major square grid.
    """
    import math
    side = math.isqrt(n)
    if side * side != n:
        return None
    for r in range(n):
        rr, cc = divmod(r, side)
        want = set()
        if cc > 0: want.add(r - 1)
        if cc < side - 1: want.add(r + 1)
        if rr > 0: want.add(r - side)
        if rr < side - 1: want.add(r + side)
        if set(adj[r]) != want:
            return None
    alist = {i: sorted(adj[i]) for i in range(n)}
    tbl = {}
    for src in range(n):
        sr, sc = divmod(src, side)
        for dst in range(n):
            if dst == src:
                continue
            dr, dc = divmod(dst, side)
            if sc != dc:
                nxt = sr * side + (sc + (1 if dc > sc else -1))
            else:
                nxt = (sr + (1 if dr > sr else -1)) * side + sc
            tbl[(src, dst)] = alist[src].index(nxt)
    return tbl

def up_down_tables(n, adj, root):
    """R11: up*/down* routing — CDG-acyclic on ANY topology (Dally-Seitz).

    Build a BFS tree from `root`. Every (src,dst) route goes UP the tree
    from src to LCA(src,dst), then DOWN to dst. Order channels by
    (tree_level, up<down): all UP links point strictly toward lower level,
    all DOWN links toward higher level => no dependency cycle can close.

    Memoryless per-dst (LCA is a static function of the pair), so it is
    compatible with the certified per-flit router. Path lengths can exceed
    shortest path on irregular graphs — that is the price of a provable
    deadlock-free FREE class; dijkstra remains available via --tables
    dijkstra for topologies separately proven acyclic.
    """
    from collections import deque
    parent = [-1]*n; level = [-1]*n; level[root] = 0
    q = deque([root])
    while q:
        u = q.popleft()
        for v in sorted(adj[u]):
            if level[v] < 0:
                level[v] = level[u]+1; parent[v] = u; q.append(v)
    if any(l < 0 for l in level):
        return None  # disconnected
    # children lists for downward walk
    children = {i: [] for i in range(n)}
    for v in range(n):
        if parent[v] >= 0:
            children[parent[v]].append(v)

    def lca(a, b):
        while level[a] > level[b]: a = parent[a]
        while level[b] > level[a]: b = parent[b]
        while a != b:
            a = parent[a]; b = parent[b]
        return a

    tbl = {}
    for src in range(n):
        nbrs = sorted(adj[src])
        pidx = {nb: i for i, nb in enumerate(nbrs)}
        for dst in range(n):
            if dst == src: continue
            l = lca(src, dst)
            if src == l:
                nxt = dst           # pure down-leg: walk into child subtree
                while parent[nxt] != src:
                    nxt = parent[nxt]
            else:
                nxt = parent[src]   # up-leg first
            tbl[(src, dst)] = pidx.get(nxt, 0)
    return tbl

def cdg_has_cycle(n, adj, tbl):
    """Channel-dependency-graph cycle detector (Dally-Seitz).
    R6 FIX: build edges from ACTUAL consecutive hops of each (src,dst)
    route — the old link-level over-approximation produced false cycles
    (e.g. vertical-then-horizontal transitions no single flit can take).
    """
    alist = {i: sorted(adj[i]) for i in range(n)}
    cdg = {}
    for s in range(n):
        for d in range(n):
            if d == s:
                continue
            # trace the route
            cur = s
            prev = None
            for _ in range(4 * n):
                p = tbl.get((cur, d))
                if p is None:
                    break
                nxt = alist[cur][p]
                if prev is not None:
                    cdg.setdefault((prev, cur), set()).add((cur, nxt))
                prev, cur = cur, nxt
                if cur == d:
                    break
    color = {}
    def dfs(u):
        color[u] = 1
        for v in cdg.get(u, ()):
            if color.get(v, 0) == 1:
                return True
            if color.get(v, 0) == 0 and dfs(v):
                return True
        color[u] = 2
        return False
    return any(color.get(l, 0) == 0 and dfs(l) for l in cdg)

